"""Rebuild the frontend's walking graph from OpenStreetMap.

The frontend ships with a hand-placed schematic graph (frontend/data/southampton.js) because OSM was
not reachable when it was built. This script keeps every named place from that file (terminals,
dock gates, venue clusters, exits: one node per line, as the file is written), snaps each one to
the nearest node of the real OSM walking network, and writes frontend/data/southampton.osm.js with
the same exports. To use it, change the import at the top of frontend/js/core/graph.js from
"southampton.js" to "southampton.osm.js".

    uv run python scripts/export_frontend_graph.py            # needs network access to OSM
    uv run python scripts/export_frontend_graph.py --simplify # merge degree-2 nodes first

Untested against live OSM at the time of writing (16 Oct 2026); check the snapped positions on the
map before trusting them, especially terminals inside the port estate where OSM footways are sparse.
"""

from __future__ import annotations

import argparse
import json
import re
from datetime import date
from pathlib import Path

import networkx as nx
from pyproj import Transformer

from sotonship26.config import load_config
from sotonship26.data.streets import load_streets

ROOT = Path(__file__).resolve().parents[1]
SCHEMATIC = ROOT / "frontend" / "data" / "southampton.js"
OUT = ROOT / "frontend" / "data" / "southampton.osm.js"
NODE_LINE = re.compile(
    r'\{\s*id:\s*"(?P<id>[^"]+)",\s*kind:\s*"(?P<kind>[^"]+)"'
    r".*?lat:\s*(?P<lat>-?[\d.]+),\s*lon:\s*(?P<lon>-?[\d.]+)"
)


def schematic_places(path: Path) -> list[dict]:
    """Named places from the schematic file, keeping the full JS object text for re-emission."""
    places = []
    for line in path.read_text(encoding="utf-8").splitlines():
        m = NODE_LINE.search(line)
        if m and m["kind"] != "junction":
            places.append(
                {
                    **m.groupdict(),
                    "lat": float(m["lat"]),
                    "lon": float(m["lon"]),
                    "src": line.strip().rstrip(","),
                }
            )
    return places


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--config", default=None)
    ap.add_argument(
        "--simplify", action="store_true", help="drop degree-2 junctions (smaller file)"
    )
    args = ap.parse_args(argv)

    cfg = load_config(args.config)
    st = cfg["streets"]
    graph = load_streets(
        st["centre"],
        radius_m=st["radius_m"],
        crs=st["crs"],
        walk_speed_mps=st["walk_speed_mps"],
        ped_per_m_per_min=st["ped_per_m_per_min"],
        bin_minutes=cfg["time"]["bin_minutes"],
        default_width_m=st["default_width_m"],
    )
    graph = graph.subgraph(max(nx.connected_components(graph), key=len)).copy()
    if args.simplify:
        graph = _merge_degree_two(graph)

    to_wgs = Transformer.from_crs(st["crs"], "EPSG:4326", always_xy=True)
    to_bng = Transformer.from_crs("EPSG:4326", st["crs"], always_xy=True)

    ids = {n: f"J{i}" for i, n in enumerate(graph.nodes)}
    nodes, edges = [], []
    for n, data in graph.nodes(data=True):
        lon, lat = to_wgs.transform(*data["pos"])
        nodes.append(
            f'  {{ id: "{ids[n]}", kind: "junction", name: "", lat: {lat:.6f}, lon: {lon:.6f} }}'
        )
    for u, v, data in graph.edges(data=True):
        edges.append(f'  ["{ids[u]}", "{ids[v]}", "street", {data["width"]:.1f}]')

    pos = {n: data["pos"] for n, data in graph.nodes(data=True)}
    for place in schematic_places(SCHEMATIC):
        x, y = to_bng.transform(place["lon"], place["lat"])
        nearest = min(pos, key=lambda n: (pos[n][0] - x) ** 2 + (pos[n][1] - y) ** 2)
        gap = ((pos[nearest][0] - x) ** 2 + (pos[nearest][1] - y) ** 2) ** 0.5
        if gap > 250:
            print(f"warning: {place['id']} is {gap:.0f} m from the nearest OSM footway node")
        nodes.append("  " + place["src"])
        cls = "gate" if place["kind"] == "gate" else "door"
        edges.append(f'  ["{place["id"]}", "{ids[nearest]}", "{cls}"]')

    OUT.write_text(
        "// GENERATED by scripts/export_frontend_graph.py. Do not edit by hand.\n"
        f"// OpenStreetMap walking network within {st['radius_m']} m of {st['centre']},\n"
        f"// fetched {date.today().isoformat()}. (c) OpenStreetMap contributors, ODbL.\n\n"
        'export { WIDTHS, LAND, CHANNEL, VIEW } from "./southampton.js";\n\n'
        "export const META = "
        + json.dumps(
            {
                "name": "Southampton city centre (OpenStreetMap)",
                "source": "OpenStreetMap via osmnx",
                "collected": date.today().isoformat(),
                "licence": "ODbL, (c) OpenStreetMap contributors",
                "synthetic": False,
                "origin": {"lat": 50.9005, "lon": -1.405},
            }
        )
        + ";\n\nexport const NODES = [\n"
        + ",\n".join(nodes)
        + "\n];\n\nexport const EDGES = [\n"
        + ",\n".join(edges)
        + "\n];\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT.relative_to(ROOT)}: {len(nodes)} nodes, {len(edges)} edges")


def _merge_degree_two(graph: nx.Graph) -> nx.Graph:
    """Collapse chains of degree-2 nodes into single edges, keeping total length and min width."""
    g = graph.copy()
    for n in [n for n in g.nodes if g.degree(n) == 2]:
        if g.degree(n) != 2:
            continue
        a, b = list(g.neighbors(n))
        if a == b or g.has_edge(a, b):
            continue
        ea, eb = g[n][a], g[n][b]
        g.add_edge(
            a,
            b,
            length=ea["length"] + eb["length"],
            cost=ea["cost"] + eb["cost"],
            width=min(ea["width"], eb["width"]),
            capacity=min(ea["capacity"], eb["capacity"]),
        )
        g.remove_node(n)
    return g


if __name__ == "__main__":
    main()
